function assertComplete(name, dict) {
  const missing = Object.keys(en).filter((k) => !(k in dict));
  const extra = Object.keys(dict).filter((k) => !(k in en));
  if (missing.length || extra.length) {
    console.error(name, { missing, extra });
    process.exit(1);
  }
}


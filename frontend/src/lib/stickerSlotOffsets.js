export function resolveSlotOffset(weaponName, slotIndex, size) {
  const key = String(weaponName || '').trim()
  const slots = STICKER_SLOT_OFFSETS[key]
  const def = slots?.[slotIndex] || { fx: 0, fy: 0, distMul: 1 }
  return {
    x: def.fx * size.x,
    y: def.fy * size.y,
    distance: def.distMul * size.z,
  }
}
